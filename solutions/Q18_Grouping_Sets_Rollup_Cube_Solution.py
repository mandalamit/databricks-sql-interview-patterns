# MAGIC ### Problem Statement
# MAGIC Produce a single query over `orders_raw` (completed, deduplicated) returning revenue by `(region, product_name)`, regional subtotals, and the grand total, labeling subtotal rows as `'ALL'`.

# COMMAND ----------

# MAGIC %sql
# MAGIC USE SCHEMA sql_interview_prep;
# MAGIC
# MAGIC WITH dedup AS (
# MAGIC   SELECT region, product_name, amount
# MAGIC   FROM orders_raw
# MAGIC   WHERE status = 'COMPLETED' AND amount IS NOT NULL
# MAGIC   QUALIFY ROW_NUMBER() OVER (PARTITION BY order_id ORDER BY updated_at DESC) = 1
# MAGIC )
# MAGIC SELECT COALESCE(region, 'ALL REGIONS') AS region,
# MAGIC        COALESCE(product_name, 'ALL PRODUCTS') AS product_name,
# MAGIC        ROUND(SUM(amount), 2) AS total_revenue,
# MAGIC        GROUPING(region) AS is_region_total,
# MAGIC        GROUPING(product_name) AS is_product_total
# MAGIC FROM dedup
# MAGIC GROUP BY ROLLUP(region, product_name)
# MAGIC ORDER BY GROUPING(region), region, GROUPING(product_name), total_revenue DESC;

# COMMAND ----------

